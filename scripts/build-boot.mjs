// OKC dynamic publish build. The platform runs `npm run build`, then ships
// bootstrap + dist/ + .env + package.json to FC and boots `node dist/boot.js`.
// vite build already produced the frontend in dist/; this script bundles the
// server into dist/server.bundled.js (deps like mysql2 inlined via esbuild,
// with a real createRequire for their CJS internals) and writes dist/boot.js:
// an ESM wrapper that loads /code/.env defaults and imports the server bundle.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const BANNER = [
  'import { createRequire as __nodeCreateRequire } from "node:module";',
  'const require = __nodeCreateRequire(import.meta.url);',
].join('\n');

await build({
  entryPoints: ['server/index.js'],
  outfile: 'dist/server.bundled.js',
  bundle: true,
  platform: 'node',
  target: 'node20.11',
  format: 'esm',
  banner: { js: BANNER },
  logLevel: 'info',
});

writeFileSync(
  'dist/boot.js',
  `// generated by scripts/build-boot.mjs: load .env defaults, then start the server.
// The FC bootstrap runs \`node dist/boot.js\` without sourcing .env; real
// environment variables (e.g. DATABASE_URL injected by the platform) win.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = fileURLToPath(new URL('.', import.meta.url));
try {
  for (const line of fs.readFileSync(path.join(HERE, '..', '.env'), 'utf8').split('\\n')) {
    const m = line.match(/^\\s*([A-Z_][A-Z0-9_]*)\\s*=\\s*(.*?)\\s*$/);
    if (!m || m[1] in process.env) continue;
    // .env 里常见 DATABASE_URL="mysql://..." 这种带成对引号的写法：
    // 引号是给 shell/解析器看的边界，不该原样进变量值。
    const raw = m[2];
    const quoted = /^(['"])([\\s\\S]*)\\1$/.exec(raw);
    process.env[m[1]] = quoted ? quoted[2] : raw;
  }
} catch {}
// FC custom runtime routes to port 3000 and injects no PORT of its own.
process.env.PORT ||= '3000';
await import('./server.bundled.js');
`
);
console.log('dist/boot.js + dist/server.bundled.js ready');
